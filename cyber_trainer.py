def local_practice(stdscr):
    commands = [
        ("whoami", "Текущий пользователь"),
        ("ip addr", "Сетевые интерфейсы и IP"),
        ("ip route", "Таблица маршрутизации"),
        ("ss -tulpn", "Слушающие порты и процессы"),
        ("ps aux", "Запущенные процессы"),
        ("systemctl --type=service --state=running", "Запущенные службы"),
        ("↩️ Назад", "")
    ]

    while True:
        labels = [f"{cmd} — {desc}" if desc else cmd for cmd, desc in commands]
        choice = arrow_menu(stdscr, "БЕЗОПАСНАЯ ПРАКТИКА", labels)
        if choice is None or choice == len(commands) - 1:
            return

        command, explanation = commands[choice]
        # Для подтверждения запуска используем отдельный экран, но тоже без ввода номера.
        confirm = arrow_menu(
            stdscr,
            "ВЫПОЛНИТЬ КОМАНДУ?",
            ["▶️ Да, выполнить", "↩️ Нет, назад"],
            f"Команда: {command}"
        )
        if confirm != 0:
            continue

        # curses временно отключаем, чтобы subprocess мог нормально показать вывод.
        curses.endwin()
        print(f"\n💻 Команда: {command}")
        print(f"📌 {explanation}")
        print("\n" + "─" * 58)
        try:
            subprocess.run(command, shell=True)
        except Exception as e:
            print(f"Ошибка: {e}")
        print("─" * 58)
        print("\nНажми Enter, чтобы вернуться в меню...")
        try:
            input()
        except EOFError:
            pass
        stdscr.clear()
        stdscr.refresh()
        add_xp(5)
        save_progress()


def progress_menu(stdscr):
    total = progress["tests"]
    correct = progress["correct"]
    accuracy = (correct / total * 100) if total else 0

    lines = [
        f"⭐ Уровень:       {level()}",
        f"✨ XP:            {progress['xp']}",
        f"📚 Тем изучено:   {len(progress['lessons'])}",
        f"🧠 Ответов:       {total}",
        f"✅ Правильных:    {correct}",
        f"🎯 Точность:      {accuracy:.0f}%",
        f"🛡️ Инцидентов:    {progress['incidents']}",
        ""
    ]

    topics = progress.get("topics") or {}
    if topics:
        lines += ["📝 РЕЗУЛЬТАТЫ ТЕСТА ПО ТЕМАМ:"]
        for t, (c, n) in topics.items():
            if n:
                lines.append(f"  {TEST_LABELS.get(t, t)}: {c}/{n} ({round(c / n * 100)}%)")
        lines.append("")

    if level() >= 5:
        lines.append("🏆 Отличный прогресс! Можно переходить к более сложным сценариям.")
    elif level() >= 3:
        lines.append("🔥 Хороший темп. Продолжай практиковаться.")
    else:
        lines.append("🚀 Начало положено. Главное — регулярная практика.")

    show_text(stdscr, "МОЙ ПРОГРЕСС", lines)


def main_menu(stdscr):
    # Включаем обработку специальных клавиш терминала: стрелки, F1 и т.д.
    stdscr.keypad(True)
    set_cursor(False)
    items = [
        "📚 Обучение",
        "🌐 Сети",
        "🧠 Тест по всем темам",
        "🌐 Знание портов",
        "🧮 Тренажёр Subnetting",
        "🎯 Распознать атаку",
        "🛡️ Стажёр SOC",
        "🎯 Свободное расследование",
        "📖 База знаний SOC",
        "🧪 Безопасная практика Linux",
        "📊 Мой прогресс",
        "🚪 Выход"
    ]
    handlers = [
        lesson_menu, network_trainer_menu, quiz, ports_quiz, subnetting_quiz,
        attack_quiz, incident_mode, free_investigation, knowledge_menu,
        local_practice, progress_menu,
    ]

    selected = 0
    while True:
        stdscr.erase()
        h, w = stdscr.getmaxyx()
        safe_addstr(stdscr, 1, 2, "🛡️  CYBER TRAINER", curses.A_BOLD)
        safe_addstr(stdscr, 2, 2, f"⭐ Уровень {level()}   |   XP: {progress['xp']}")
        safe_addstr(stdscr, 3, 2, "═" * min(58, max(10, w - 4)))

        for i, item in enumerate(items):
            attr = curses.A_REVERSE | curses.A_BOLD if i == selected else curses.A_NORMAL
            prefix = "➤ " if i == selected else "  "
            safe_addstr(stdscr, 5 + i, 2, prefix + item, attr)

        safe_addstr(stdscr, h - 2, 2, "↑/↓ выбор • Enter открыть • Esc выйти")
        stdscr.refresh()

        key = stdscr.getch()
        if key in (curses.KEY_UP, ord("k")):
            selected = (selected - 1) % len(items)
        elif key in (curses.KEY_DOWN, ord("j")):
            selected = (selected + 1) % len(items)
        elif key in (curses.KEY_ENTER, 10, 13):
            if selected == len(items) - 1:
                return
            handlers[selected](stdscr)
            set_cursor(False)
        elif key == 27:
            return


def main():
    try:
        curses.wrapper(lambda scr: main_menu(KeyScreen(scr)))
    except KeyboardInterrupt:
        pass
    print("\nДо встречи, будущий специалист по кибербезопасности! 🛡️")


if __name__ == "__main__":
    main()
