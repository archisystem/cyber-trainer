def incident_mode(stdscr):
    incident = random.choice(INCIDENTS)
    score = 0
    actions = []
    mistakes = 0
    learned = []

    intro = [
        incident["title"],
        "",
        "📖 СИТУАЦИЯ:",
        incident["story"],
        "",
        "🎓 ТВОЯ ЗАДАЧА:",
        "Не просто угадать правильную команду, а понять логику расследования.",
        "",
        "Правило: сначала факты → затем связь артефактов → затем вывод → containment."
    ]
    show_text(stdscr, "🛡️ НОВЫЙ ИНЦИДЕНТ", intro)

    for step_no, step in enumerate(incident["steps"], 1):
        labels = [f"{cmd} — {desc}" for cmd, desc, _ in step["options"]]
        selected = arrow_menu(
            stdscr,
            f"СТАЖЁР SOC • ШАГ {step_no}/{len(incident['steps'])}",
            labels,
            "↑/↓ выбор • Enter выполнить действие • Esc выйти"
        )
        if selected is None:
            return

        command, description, points = step["options"][selected]
        actions.append(command)
        score += points
        if points < 0:
            mistakes += 1

        if points >= 2:
            result = [
                "✅ Хорошее действие! +2 балла",
                f"💻 Выбрано: {command}",
                f"💡 {step['hint']}",
            ]
        elif points == 1:
            result = [
                "🟡 Допустимое действие, но не оптимальное. +1 балл",
                f"💻 Выбрано: {command}",
                f"💡 {step['hint']}",
            ]
        elif points == 0:
            result = [
                "⚪ Действие не помогает расследованию. +0 баллов",
                f"💻 Выбрано: {command}",
                f"💡 {step['hint']}",
            ]
        else:
            result = [
                "🔴 Рискованное действие! Баллы снижены.",
                f"💻 Выбрано: {command}",
                f"💡 {step['hint']}",
            ]

        show_text(stdscr, f"Разбор шага {step_no}", result)

        # Главное изменение: после каждого решения программа расширяет знания.
        if command in COMMAND_KNOWLEDGE:
            learned.append(command)
            show_knowledge(stdscr, command, points)

    progress["incidents"] += 1
    bonus = 0
    if score >= len(incident["steps"]) * 2 - 1:
        bonus = 30
        grade = "🏆 Отлично"
    elif score >= len(incident["steps"]):
        bonus = 20
        grade = "🔥 Хорошо"
    elif score >= 2:
        bonus = 10
        grade = "👍 Нормально, но есть что улучшить"
    else:
        grade = "📚 Стоит повторить порядок triage"

    add_xp(max(0, bonus))
    save_progress()

    lines = [
        f"{grade}",
        f"📊 Баллы расследования: {score}",
        f"⚠️ Ошибок/рискованных действий: {mistakes}",
        f"✨ Бонус: +{bonus} XP",
        "",
        "🔎 СОБРАННЫЕ АРТЕФАКТЫ / IOC:",
    ]
    lines.extend([f"• {item}" for item in incident["evidence"]])
    lines.extend([
        "",
        "📝 ВЫВОД АНАЛИТИКА:",
        incident["final"],
        "",
        "📋 ТВОЙ ПОРЯДОК ДЕЙСТВИЙ:",
    ])
    lines.extend([f"{i}. {action}" for i, action in enumerate(actions, 1)])

    if learned:
        lines.extend([
            "",
            "🎓 ЧТО ТЫ ЗАКРЕПИЛ В ЭТОМ РАССЛЕДОВАНИИ:",
        ])
        unique_learned = list(dict.fromkeys(learned))
        lines.extend([f"• {cmd}" for cmd in unique_learned])

    show_text(stdscr, f"ИТОГ • {incident['title']}", lines)


