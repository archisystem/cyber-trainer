def attack_quiz(stdscr):
    questions = random.sample(ATTACKS, min(8, len(ATTACKS)))
    score = 0

    for number, attack in enumerate(questions, 1):
        other_names = [a["name"] for a in ATTACKS if a["name"] != attack["name"]]
        choices = [attack["name"]] + random.sample(other_names, 3)
        random.shuffle(choices)

        description = [
            f"СИТУАЦИЯ {number}/{len(questions)}",
            "",
            "Что происходит:",
            attack["process"],
            "",
            "Признаки:",
            attack["signs"],
            "",
            "🎯 Какой это тип атаки?"
        ]

        show_text(stdscr, "🎯 РАСПОЗНАЙ АТАКУ", description)
        selected = arrow_menu(
            stdscr,
            "ВЫБЕРИ ОТВЕТ",
            choices,
            "↑/↓ выбор • Enter • Esc",
            prompt="🎯 Какой это тип атаки?",
            hint=f"💡 Как от этого защищаются: {attack['defense']}",
        )
        if selected is None:
            return

        answer = choices[selected]
        if answer == attack["name"]:
            score += 1
            result = "✅ Правильно!"
        else:
            result = f"❌ Неправильно. Правильный ответ: {attack['name']}."

        show_text(stdscr, "📚 РАЗБОР", [
            result,
            "",
            f"🛡️ Атака: {attack['name']}",
            f"📌 Что это: {attack['description']}",
            "",
            f"🔎 Признаки: {attack['signs']}",
            "",
            f"🛡️ Защита: {attack['defense']}",
        ])

    add_xp(score * 15)
    progress["tests"] += 1
    progress["correct"] += score
    save_progress()

    accuracy = round(score / len(questions) * 100)
    show_text(stdscr, "🏁 РЕЗУЛЬТАТ: РАСПОЗНАВАНИЕ АТАК", [
        f"Правильных ответов: {score}/{len(questions)}",
        f"Точность: {accuracy}%",
        f"XP: +{score * 15}",
        "",
        "Главное — узнавать атаку по процессу и признакам, "
        "а не только по ключевому слову."
    ])


