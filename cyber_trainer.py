def norm(value):
    return " ".join(value.lower().strip().split())


def command_matches(user, answer):
    user = norm(user)
    answer = norm(answer)

    if user == answer:
        return True

    if answer in ("ping", "traceroute"):
        return user.startswith(answer + " ") or user == answer

    return False


