def draw_box(stdscr, title, lines, selected=0, footer=None):
    stdscr.erase()
    h, w = stdscr.getmaxyx()

    border = "═"
    width = max(20, min(w - 4, 78))
    left = max(1, (w - width) // 2)

    safe_addstr(stdscr, 1, left, "╔" + border * (width - 2) + "╗")
    safe_addstr(stdscr, 2, left, "║" + f"  {title}  ".center(width - 2) + "║")
    safe_addstr(stdscr, 3, left, "╠" + border * (width - 2) + "╣")

    y = 4
    for line in lines:
        for part in wrap_line(line, max(10, width - 8)):
            if y >= h - 3:
                break
            safe_addstr(stdscr, y, left + 3, part[:width - 6])
            y += 1

    safe_addstr(stdscr, min(h - 3, y), left, "╚" + border * (width - 2) + "╝")
    if footer:
        safe_addstr(stdscr, h - 2, left + 2, footer[:width - 4], curses.A_BOLD)
    stdscr.refresh()


def menu(stdscr, title, items, subtitle="↑↓ выбор   Enter — выбрать   Q — назад"):
    """Полноценное меню со скроллингом для длинных списков."""
    if not items:
        return None

    selected = 0
    offset = 0

    while True:
        h, _ = stdscr.getmaxyx()
        visible = max(3, h - 7)

        if selected < offset:
            offset = selected
        elif selected >= offset + visible:
            offset = selected - visible + 1

        lines = []
        end = min(len(items), offset + visible)
        for i in range(offset, end):
            prefix = "➜ " if i == selected else "  "
            lines.append(prefix + items[i])

        if offset > 0:
            lines.insert(0, "↑ ещё выше")
        if end < len(items):
            lines.append("↓ ещё ниже")

        draw_box(stdscr, title, lines, selected - offset, subtitle)

        key = stdscr.getch()

        if key in (curses.KEY_UP, ord("k")):
            selected = (selected - 1) % len(items)

        elif key in (curses.KEY_DOWN, ord("j")):
            selected = (selected + 1) % len(items)

        elif key in (10, 13, curses.KEY_ENTER):
            return selected

        elif key in (ord("q"), ord("Q"), 27):
            return None


